-- Creación de recepciones de órdenes de compra
-- =====================================================

-- 1. Cabecera de recepción

CREATE TABLE purchase_receipt (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  number VARCHAR(30) NOT NULL,

                                  purchase_order_id BIGINT NOT NULL,

                                  warehouse_id BIGINT NOT NULL,

                                  document VARCHAR(255) NOT NULL,

                                  received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

                                  received_by VARCHAR(255) NOT NULL,

                                  CONSTRAINT uk_purchase_receipt_number
                                      UNIQUE (number),

                                  CONSTRAINT fk_purchase_receipt_purchase_order
                                      FOREIGN KEY (purchase_order_id)
                                          REFERENCES purchase_order(id),

                                  CONSTRAINT fk_purchase_receipt_warehouse
                                      FOREIGN KEY (warehouse_id)
                                          REFERENCES warehouse(id)
);

-- Índices para consultas por orden y fecha

CREATE INDEX idx_purchase_receipt_order
    ON purchase_receipt(purchase_order_id);

CREATE INDEX idx_purchase_receipt_received_at
    ON purchase_receipt(received_at);


-- 2. Detalles de recepción

CREATE TABLE purchase_receipt_line (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       receipt_id BIGINT NOT NULL,

                                       purchase_order_line_id BIGINT NOT NULL,

                                       quantity NUMERIC(19, 3) NOT NULL,

                                       unit_cost NUMERIC(19, 2) NOT NULL,

                                       total NUMERIC(19, 2) NOT NULL,

                                       inventory_movement_id BIGINT NOT NULL,

                                       CONSTRAINT fk_purchase_receipt_line_receipt
                                           FOREIGN KEY (receipt_id)
                                               REFERENCES purchase_receipt(id),

                                       CONSTRAINT fk_purchase_receipt_line_order_line
                                           FOREIGN KEY (purchase_order_line_id)
                                               REFERENCES purchase_order_line(id),

                                       CONSTRAINT fk_purchase_receipt_line_movement
                                           FOREIGN KEY (inventory_movement_id)
                                               REFERENCES inventory_movement(id),

                                       CONSTRAINT chk_purchase_receipt_line_quantity
                                           CHECK (quantity > 0),

                                       CONSTRAINT chk_purchase_receipt_line_unit_cost
                                           CHECK (unit_cost > 0),

                                       CONSTRAINT chk_purchase_receipt_line_total
                                           CHECK (total >= 0)
);

-- Índices para relaciones y búsquedas

CREATE INDEX idx_purchase_receipt_line_receipt
    ON purchase_receipt_line(receipt_id);

CREATE INDEX idx_purchase_receipt_line_order_line
    ON purchase_receipt_line(purchase_order_line_id);

CREATE INDEX idx_purchase_receipt_line_movement
    ON purchase_receipt_line(inventory_movement_id);
