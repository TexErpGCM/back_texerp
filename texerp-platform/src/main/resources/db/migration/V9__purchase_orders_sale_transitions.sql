-- Sprint 4: ordenes de compra y lineas (corresponde a las entidades actuales).
CREATE TABLE purchase_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(30),
    supplier_id BIGINT NOT NULL,
    ordered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL,
    total NUMERIC(19,2) NOT NULL DEFAULT 0,
    decided_at TIMESTAMP WITH TIME ZONE,
    decided_by VARCHAR(255),
    rejection_reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_purchase_order_number UNIQUE (number),
    CONSTRAINT fk_purchase_order_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(id),
    CONSTRAINT ck_purchase_order_total CHECK (total >= 0),
    CONSTRAINT ck_purchase_order_status CHECK (status IN ('PENDING_APPROVAL', 'APPROVED', 'REJECTED'))
);

CREATE TABLE purchase_order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL,
    variant_id BIGINT NOT NULL,
    quantity NUMERIC(19,3) NOT NULL,
    received_quantity NUMERIC(19,3) NOT NULL DEFAULT 0,
    unit_cost NUMERIC(19,2) NOT NULL,
    total NUMERIC(19,2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_purchase_order_line_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_order(id),
    CONSTRAINT fk_purchase_order_line_variant FOREIGN KEY (variant_id) REFERENCES product_variant(id),
    CONSTRAINT ck_purchase_order_line_quantity CHECK (quantity > 0 AND received_quantity >= 0 AND received_quantity <= quantity),
    CONSTRAINT ck_purchase_order_line_cost CHECK (unit_cost > 0 AND total >= 0)
);

CREATE INDEX idx_purchase_order_supplier ON purchase_order (supplier_id);
CREATE INDEX idx_purchase_order_status ON purchase_order (status);
CREATE INDEX idx_purchase_order_line_order ON purchase_order_line (purchase_order_id);
CREATE INDEX idx_purchase_order_line_variant ON purchase_order_line (variant_id);

-- Los permisos nuevos deben asignarse a un rol existente para poder utilizar los endpoints.
INSERT INTO role_permission (role_id, permission)
SELECT r.id, p.permission
FROM app_role r
CROSS JOIN (VALUES
    ('SALE_DISPATCH'), ('SALE_CANCEL'),
    ('PURCHASE_ORDER_READ'), ('PURCHASE_ORDER_CREATE'), ('PURCHASE_ORDER_APPROVE')
) AS p(permission)
WHERE r.name = 'ADMINISTRADOR'
ON CONFLICT DO NOTHING;
