
CREATE SCHEMA IF NOT EXISTS texerp_dw;

CREATE TABLE IF NOT EXISTS texerp_dw.fact_inventory (
                                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                        snapshot_date DATE NOT NULL,
                                                        variant_id BIGINT NOT NULL,
                                                        warehouse_id BIGINT NOT NULL,

                                                        available_quantity NUMERIC(19, 3) NOT NULL,
    reserved_quantity NUMERIC(19, 3) NOT NULL,
    minimum_quantity NUMERIC(19, 3) NOT NULL,

    unit_cost_snapshot NUMERIC(19, 4),
    available_inventory_value NUMERIC(23, 4),

    source_updated_at TIMESTAMPTZ,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uk_fact_inventory_snapshot
    UNIQUE (snapshot_date, variant_id, warehouse_id),

    CONSTRAINT ck_fact_inventory_available
    CHECK (available_quantity >= 0),

    CONSTRAINT ck_fact_inventory_reserved
    CHECK (reserved_quantity >= 0),

    CONSTRAINT ck_fact_inventory_minimum
    CHECK (minimum_quantity >= 0)
    );

CREATE INDEX IF NOT EXISTS idx_fact_inventory_date
    ON texerp_dw.fact_inventory(snapshot_date);

CREATE INDEX IF NOT EXISTS idx_fact_inventory_warehouse_date
    ON texerp_dw.fact_inventory(warehouse_id, snapshot_date);

CREATE INDEX IF NOT EXISTS idx_fact_inventory_variant_date
    ON texerp_dw.fact_inventory(variant_id, snapshot_date);

COMMENT ON TABLE texerp_dw.fact_inventory IS
    'Fotografias de inventario capturadas desde el sistema operacional';

COMMENT ON COLUMN texerp_dw.fact_inventory.unit_cost_snapshot IS
    'Costo actual de la variante al momento de captura; no equivale necesariamente al costo promedio historico';

COMMENT ON COLUMN texerp_dw.fact_inventory.available_inventory_value IS
    'Valor de unidades disponibles multiplicadas por el costo capturado';
