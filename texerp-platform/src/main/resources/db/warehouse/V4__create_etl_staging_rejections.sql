
CREATE TABLE IF NOT EXISTS texerp_dw.staging_rejections (
                                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                            execution_id BIGINT NOT NULL,
                                                            job_id BIGINT NOT NULL,
                                                            source_table VARCHAR(100) NOT NULL,
    source_record_id VARCHAR(100),
    rejection_reason TEXT NOT NULL,
    raw_data JSONB,
    rejected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_staging_rejections_execution
    FOREIGN KEY (execution_id)
    REFERENCES texerp_dw.etl_execution(id),

    CONSTRAINT fk_staging_rejections_job
    FOREIGN KEY (job_id)
    REFERENCES texerp_dw.etl_job(id)
    );

CREATE INDEX IF NOT EXISTS idx_staging_rejections_execution
    ON texerp_dw.staging_rejections(execution_id);
