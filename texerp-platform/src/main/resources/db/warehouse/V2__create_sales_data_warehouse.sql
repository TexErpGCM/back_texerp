-- 1. STAGING: una fila por línea de venta
CREATE TABLE texerp_dw.stg_sales (
                                     sale_line_id BIGINT PRIMARY KEY,
                                     sale_id BIGINT NOT NULL,
                                     sale_number VARCHAR(100),
                                     customer_id BIGINT NOT NULL,
                                     warehouse_id BIGINT NOT NULL,
                                     variant_id BIGINT NOT NULL,
                                     sale_status VARCHAR(50) NOT NULL,
                                     confirmed_at TIMESTAMPTZ NOT NULL,
                                     source_updated_at TIMESTAMPTZ NOT NULL,
                                     quantity NUMERIC NOT NULL,
                                     unit_price NUMERIC NOT NULL,
                                     unit_cost NUMERIC NOT NULL,
                                     discount_amount NUMERIC NOT NULL,
                                     tax_amount NUMERIC NOT NULL,
                                     subtotal NUMERIC NOT NULL,
                                     total NUMERIC NOT NULL,
                                     staged_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. DIMENSIÓN CLIENTE (SCD TIPO 2)
CREATE TABLE texerp_dw.dim_customer (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        customer_id BIGINT NOT NULL,
                                        document VARCHAR(100) NOT NULL,
                                        name VARCHAR(255) NOT NULL,
                                        type VARCHAR(100) NOT NULL,
                                        classification VARCHAR(100),
                                        active BOOLEAN NOT NULL,
                                        valid_from TIMESTAMPTZ NOT NULL,
                                        valid_to TIMESTAMPTZ,
                                        is_current BOOLEAN NOT NULL DEFAULT TRUE,
                                        CONSTRAINT ck_dim_customer_dates
                                            CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE UNIQUE INDEX ux_dim_customer_current
    ON texerp_dw.dim_customer(customer_id)
    WHERE is_current = TRUE;

-- 3. DIMENSIÓN PRODUCTO / VARIANTE (SCD TIPO 2)
CREATE TABLE texerp_dw.dim_product (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       variant_id BIGINT NOT NULL,
                                       product_id BIGINT NOT NULL,
                                       product_code VARCHAR(100) NOT NULL,
                                       product_name VARCHAR(255) NOT NULL,
                                       sku VARCHAR(100) NOT NULL,
                                       color VARCHAR(100) NOT NULL,
                                       pattern VARCHAR(100),
                                       fabric_type VARCHAR(100) NOT NULL,
                                       sale_price NUMERIC NOT NULL,
                                       active BOOLEAN NOT NULL,
                                       valid_from TIMESTAMPTZ NOT NULL,
                                       valid_to TIMESTAMPTZ,
                                       is_current BOOLEAN NOT NULL DEFAULT TRUE,
                                       CONSTRAINT ck_dim_product_dates
                                           CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE UNIQUE INDEX ux_dim_product_current
    ON texerp_dw.dim_product(variant_id)
    WHERE is_current = TRUE;

-- 4. DIMENSIÓN BODEGA (SCD TIPO 2)
CREATE TABLE texerp_dw.dim_warehouse (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         warehouse_id BIGINT NOT NULL,
                                         code VARCHAR(100) NOT NULL,
                                         name VARCHAR(255) NOT NULL,
                                         location VARCHAR(255) NOT NULL,
                                         active BOOLEAN NOT NULL,
                                         valid_from TIMESTAMPTZ NOT NULL,
                                         valid_to TIMESTAMPTZ,
                                         is_current BOOLEAN NOT NULL DEFAULT TRUE,
                                         CONSTRAINT ck_dim_warehouse_dates
                                             CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE UNIQUE INDEX ux_dim_warehouse_current
    ON texerp_dw.dim_warehouse(warehouse_id)
    WHERE is_current = TRUE;

-- 5. HECHOS DE VENTAS
CREATE TABLE texerp_dw.fact_sales (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      sale_line_id BIGINT NOT NULL UNIQUE,
                                      sale_id BIGINT NOT NULL,
                                      sale_number VARCHAR(100),
                                      customer_key BIGINT NOT NULL
                                          REFERENCES texerp_dw.dim_customer(id),
                                      product_key BIGINT NOT NULL
                                          REFERENCES texerp_dw.dim_product(id),
                                      warehouse_key BIGINT NOT NULL
                                          REFERENCES texerp_dw.dim_warehouse(id),
                                      sale_status VARCHAR(50) NOT NULL,
                                      confirmed_at TIMESTAMPTZ NOT NULL,
                                      quantity NUMERIC NOT NULL,
                                      unit_price NUMERIC NOT NULL,
                                      unit_cost NUMERIC NOT NULL,
                                      discount_amount NUMERIC NOT NULL,
                                      tax_amount NUMERIC NOT NULL,
                                      subtotal NUMERIC NOT NULL,
                                      total NUMERIC NOT NULL,
                                      source_updated_at TIMESTAMPTZ NOT NULL,
                                      loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX ix_fact_sales_confirmed_at
    ON texerp_dw.fact_sales(confirmed_at);

CREATE INDEX ix_fact_sales_customer
    ON texerp_dw.fact_sales(customer_key);

CREATE INDEX ix_fact_sales_product
    ON texerp_dw.fact_sales(product_key);

CREATE INDEX ix_fact_sales_warehouse
    ON texerp_dw.fact_sales(warehouse_key);

CREATE INDEX ix_stg_sales_updated_at
    ON texerp_dw.stg_sales(source_updated_at);
