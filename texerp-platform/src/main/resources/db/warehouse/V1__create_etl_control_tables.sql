
CREATE TABLE IF NOT EXISTS texerp_dw.etl_job (
                                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                 name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    allow_parallel BOOLEAN NOT NULL DEFAULT FALSE,
    cron_expression VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

CREATE TABLE IF NOT EXISTS texerp_dw.etl_execution (
                                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                       job_id BIGINT NOT NULL
                                                       REFERENCES texerp_dw.etl_job(id),
    previous_execution_id BIGINT
    REFERENCES texerp_dw.etl_execution(id),
    trigger_type VARCHAR(20) NOT NULL
    CHECK (trigger_type IN ('MANUAL', 'SCHEDULED', 'RETRY')),
    status VARCHAR(20) NOT NULL
    CHECK (status IN (
           'PENDING', 'RUNNING',
           'SUCCESS', 'FAILED'
                     )),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    watermark_from TIMESTAMPTZ,
    watermark_to TIMESTAMPTZ,
    records_read BIGINT NOT NULL DEFAULT 0,
    records_written BIGINT NOT NULL DEFAULT 0,
    records_rejected BIGINT NOT NULL DEFAULT 0,
    failed_step VARCHAR(100),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

CREATE TABLE IF NOT EXISTS texerp_dw.etl_watermark (
                                                       job_id BIGINT PRIMARY KEY
                                                       REFERENCES texerp_dw.etl_job(id),
    last_successful_watermark TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

CREATE UNIQUE INDEX IF NOT EXISTS
    ux_etl_execution_active_job
    ON texerp_dw.etl_execution(job_id)
    WHERE status IN ('PENDING', 'RUNNING');
