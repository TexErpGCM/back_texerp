
CREATE TABLE IF NOT EXISTS texerp_dw.etl_alert (
                                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                   execution_id BIGINT NOT NULL
                                                   REFERENCES texerp_dw.etl_execution(id),

    alert_type VARCHAR(100) NOT NULL,

    source_record_id VARCHAR(100) NOT NULL,

    message TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_etl_alert_execution_record_type
    UNIQUE (
               execution_id,
               alert_type,
               source_record_id
           )
    );

CREATE INDEX IF NOT EXISTS idx_etl_alert_execution
    ON texerp_dw.etl_alert(execution_id);
